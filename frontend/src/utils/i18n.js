/**
 * Resolves localized strings dynamically, substituting parameters
 */
export const translate = (lang, key, params = {}) => {
  const selectedLang = translations[lang] || translations['English'];
  let text = selectedLang[key] || translations['English'][key] || key;
  
  Object.keys(params).forEach(p => {
    text = text.replace(`{${p}}`, params[p]);
  });
  
  return text;
};
